#!/bin/bash
# 気象庁「世界の地点別平年値（領域・国別に探す）」から選定した37地点の
# 個別ページ (NrmMonth.php) を取得して data/raw/world_pages/ に保存する。
set -e
OUT="/Users/tcsstaff/Documents/Claude/climograph/data/raw/world_pages"
mkdir -p "$OUT"

# country_jp:city_jp:stn:note
STATIONS="
アメリカ合衆国:ニューヨーク:72503:
カナダ:トロント:71508:
メキシコ:メキシコシティ:76680:
ブラジル:サンパウロ:83781:
アルゼンチン:ブエノスアイレス:87585:
チリ:サンティアゴ:85574:
ペルー:リマ:84628:
イギリス:ロンドン:03772:ヒースロー空港（ロンドン中心部に観測所が無いための代替）
フランス:パリ:07149:オルリー空港
イタリア:トリノ:16061:気象庁データにローマの観測地点が無いための代替
ドイツ:ベルリン:10384:
スペイン:マドリード:8222:
ポルトガル:リスボン:8535:
ロシア:モスクワ:27612:
ウクライナ:キーウ:33345:
ノルウェー:オスロ:1384:
フィンランド:ヘルシンキ:2974:
アイスランド:レイキャビク:4030:
トルコ:アンカラ:17130:
エジプト:カイロ:62378:ヘルワン（カイロ首都圏、気象庁の代表観測地点）
モロッコ:カサブランカ:60155:
チュニジア:チュニス:60715:
エチオピア:アディスアベバ:63450:
ケニア:ナイロビ:63740:
サウジアラビア:リヤド:40438:
中国:ペキン:54511:
香港:ホンコン:45004:
韓国:ソウル:47108:
モンゴル:ウランバートル:44292:
インド:ニューデリー:42182:
スリランカ:コロンボ:43466:
パキスタン:カラチ:41780:
タイ:バンコク:48455:
マレーシア:クアラルンプール:48647:
インドネシア:ジャカルタ:96749:スカルノハッタ国際空港
オーストラリア:シドニー:94767:
カザフスタン:アルマトイ:36870:
"

echo "$STATIONS" | while IFS=: read -r country city stn note; do
  [ -z "$stn" ] && continue
  f="$OUT/nrm_$stn.html"
  if [ ! -s "$f" ]; then
    curl -sL -m 15 "https://www.data.jma.go.jp/gmd/cpd/monitor/nrmlist/NrmMonth.php?stn=$stn" -o "$f"
    sleep 0.3
  fi
  echo "fetched $stn ($country/$city) -> $(wc -c < "$f") bytes"
done
